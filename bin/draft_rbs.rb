# Builds a draft RBS for a gem from several sources and shows where they
# agree, so signatures start from evidence instead of guesses.
#
# Usage: ruby draft_rbs.rb --observed a.types.json [b.types.json ...] \
#            [--tyda tyda.rbs] [--existing gems/foo/1.2/foo.rbs] [--ns Foo]
#
#   --observed  output of observe_types.rb (OBSERVE_OUT.json), one per test
#               run; merged. Only calls that returned normally count, so a
#               shape that only raised (a negative test) is left out.
#   --tyda      RBS from a static inference tool run on lib + tests
#               (e.g. `tyda lib test > tyda.rbs`); used for methods the
#               tests never called and for class/module/superclass info.
#   --existing  current signatures, to report differences.
#   --ns        only methods under this namespace (default: everything).
#
# Prints the draft to stdout. Each method gets a comment with its sources:
#   # observed 8/9 calls (raises: TypeError) | tyda: (*untyped) -> untyped
# Treat it as a draft: name parameters and narrow types by reading the source.
require "json"; require "set"; require "rbs"
args = { observed: [], tyda: nil, existing: nil, ns: nil }
cur = nil
ARGV.each do |a|
  case a
  when "--observed" then cur = :observed
  when "--tyda", "--existing", "--ns" then cur = a.delete_prefix("--").to_sym
  else cur == :observed ? args[:observed] << a : (args[cur] = a; cur = nil)
  end
end
abort "need --observed or --tyda" if args[:observed].empty? && !args[:tyda]

# --- merge observations
obs = {}
args[:observed].each do |f|
  JSON.parse(File.read(f)).each do |key, d|
    o = obs[key] ||= { "calls" => 0, "ok_calls" => 0, "kinds" => {}, "params" => Hash.new { |h, k| h[k] = Set.new },
                       "block" => Set.new, "returns" => Set.new, "raises" => Set.new }
    o["calls"] += d["calls"]; o["ok_calls"] += d["ok_calls"]; o["kinds"].merge!(d["kinds"])
    d["params"].each { |l, ts| o["params"][l].merge(ts) }
    o["block"].merge(d["block"]); o["returns"].merge(d["returns"]); o["raises"].merge(d["raises"])
  end
end

# --- read RBS files (tyda, existing)
def load_rbs(path)
  return {} unless path
  _, _, decls = RBS::Parser.parse_signature(File.read(path))
  out = {}
  walk = lambda do |decl, ns|
    return unless decl.is_a?(RBS::AST::Declarations::Class) || decl.is_a?(RBS::AST::Declarations::Module)
    name = decl.name.to_s.delete_prefix("::")
    full = ns.empty? || decl.name.absolute? ? name : "#{ns}::#{name}"
    info = out[full] ||= { kind: decl.is_a?(RBS::AST::Declarations::Class) ? "class" : "module",
                           super: (decl.super_class&.name&.to_s if decl.respond_to?(:super_class)), methods: {} }
    decl.members.each do |m|
      case m
      when RBS::AST::Members::MethodDefinition
        sep = m.kind == :singleton ? "." : "#"
        info[:methods]["#{full}#{sep}#{m.name}"] = m.overloads.map { |o| o.method_type.to_s }.join(" | ")
      when RBS::AST::Declarations::Base then walk.(m, full)
      end
    end
  end
  decls.each { |d| walk.(d, "") }
  out
end
tyda = load_rbs(args[:tyda])
existing = load_rbs(args[:existing])
tyda_methods = tyda.values.flat_map { |c| c[:methods].to_a }.to_h
existing_methods = existing.values.flat_map { |c| c[:methods].to_a }.to_h

# --- type rendering
def union(types)
  ts = types.to_a.map { |t| t == "(none)" ? nil : t }.compact.uniq
  return "untyped" if ts.empty?
  nilable = ts.delete("nil")
  ts = ts.map { |t| t.include?("(anon)") ? "untyped" : t }.uniq
  ts = ["untyped"] if ts.include?("untyped")
  body = ts.empty? ? "nil" : (ts.size == 1 ? ts.first : ts.sort.join(" | "))
  return body if body == "nil" || body == "untyped" || !nilable
  ts.size == 1 ? "#{body}?" : "(#{body})?"
end

def params_sig(o)
  req = []; opt = []; rest = nil; kw = []; krest = nil
  o["kinds"].each do |label, (kind, name)|
    t = union(o["params"][label] || [])
    case kind
    when "req" then req << "#{t} #{name}"
    when "opt" then opt << "?#{t} #{name}"
    when "rest" then rest = "*#{t} #{name}"
    when "keyreq" then kw << "#{name}: #{t}"
    when "key" then kw << "?#{name}: #{t}"
    when "keyrest" then krest = "**#{t} #{name}"
    end
  end
  [*req, *opt, rest, *kw, krest].compact.join(", ")
end

def block_sig(o)
  b = o["block"].to_a
  return "" if b == ["no"] || b.empty?
  b.include?("no") ? " ?{ (?) -> untyped }" : " { (?) -> untyped }"
end

# --- collect methods per owner
keys = (obs.keys | tyda_methods.keys | existing_methods.keys)
keys.select! { |k| k.start_with?(args[:ns]) } if args[:ns]
owners = Hash.new { |h, k| h[k] = [] }
keys.each { |k| owner, sep, name = k.partition(/[.#](?=[^.#:]+\z)/); owners[owner] << [k, sep, name] }

missing_in_existing = []
puts "# Draft generated by draft_rbs.rb. Review every line against the source."
owners.sort.each do |owner, ms|
  info = tyda[owner] || existing[owner] || { kind: "class" }
  sup = info[:super] && info[:super] != "Object" ? " < #{info[:super]}" : ""
  puts "", "#{info[:kind]} #{owner}#{info[:kind] == 'class' ? sup : ''}"
  ms.sort_by { |_, sep, name| [sep == "." ? 0 : 1, name] }.each do |key, sep, name|
    o = obs[key]
    srcs = []
    if o
      r = o["raises"].map { |x| x.delete_prefix("raise ") }.to_a
      srcs << "observed #{o['ok_calls']}/#{o['calls']} calls#{r.empty? ? '' : " (raises: #{r.join(', ')})"}"
    else
      srcs << "not observed"
    end
    srcs << "tyda: #{tyda_methods[key]}" if tyda_methods[key]
    srcs << "existing: #{existing_methods[key]}" if existing_methods[key]
    sig =
      if o && o["ok_calls"] > 0
        "(#{params_sig(o)})#{block_sig(o)} -> #{union(o['returns'])}"
      elsif tyda_methods[key]
        tyda_methods[key]
      else
        "(*untyped) -> untyped"
      end
    missing_in_existing << key if !existing.empty? && o && o["ok_calls"] > 0 && !existing_methods.key?(key)
    puts "  # #{srcs.join(' | ')}"
    puts "  def #{sep == '.' ? 'self.' : ''}#{name}: #{sig}"
  end
  puts "end"
end
unless missing_in_existing.empty?
  warn "Called by the tests but not in --existing:"
  missing_in_existing.each { |k| warn "  #{k}" }
end
